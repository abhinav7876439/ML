def actives2(s, M):   ##  How active resources (M) are allocated among state
    """
    Returns (i, a) where:
    - states 0 to i-1 are active
    - state i is active with number of bandits a
    """
    i = 0
    while i < len(s) and sum(s[:i]) < M:
        i += 1
    if i == 0:
        return 0, M
    elif i >= len(s):
        return len(s) - 1, s[-1]
    else:
        return i - 1, M - sum(s[:i - 1])    ## i: Index of the last state that receives active resources,   a: Number of active resources allocated to state i

"Returns the new number of bandits in each state after transition"

def simulate_one_step(states,M,P0,P1):    ## It simulates how the states of bandits evolve after one decision step, given the allocation of active resources and the state-transition probabilities
    i, a = actives2(states, M)              ## It returns the new number of bandits in each state after transitions
    n = len(states)
    data = []
    for j in range(i):
        data.append(np.random.multinomial(states[j], P1[j]))
    data.append(np.random.multinomial(a, P1[i]))
    data.append(np.random.multinomial(states[i]-a, P0[i]))
    for j in range(i+1,n):
        data.append(np.random.multinomial(states[j], P0[j]))
    return sum(data)    # Compute the total transition outcomes using sum(data), returning the resulting "next state".

" It (reward_one_step) could be used in an iterative process to track the cumulative rewards during simulations, guiding the optimization of policies"

def reward_one_step(states,M,R0,R1):  ## It calculates the reward based on the current states, the active resources allocated to each state and the reward matrices for active and passive states
    i, a = actives2(states,M)
    if i < len(R0):                               # If total number of active states is less than the total number of states
        return (np.dot(states[0:i],R1[0:i])+a*R1[i]+(states[i]-a)*R0[i]+np.dot(states[i+1:],R0[i+1:]))      # average reward received
    else:
        return (np.dot(states[0:i],R1[0:i])+a*R1[i]+(states[i]-a)*R0[i])

"It is necessary to reorder the states, transitions and rewards according to a specific policy or sorting criterion"

def sort_data(P0,P1,R0,R1,states,order):      ## order = Activation States for LP
    # Convert input matrices to NumPy arrays if they are not already
    P0 = np.array(P0)
    P1 = np.array(P1)
    R0 = np.array(R0)
    R1 = np.array(R1)
    n = len(order)
    states = np.array(states)
    new_P0 = np.zeros((n,n))
    new_P1 = np.zeros((n,n))
    new_R0 = np.zeros(n)
    new_R1 = np.zeros(n)
    new_states = np.zeros(n, dtype=int)
    for i in range(n):
        for j in range(n):
            new_P0[i,j] = P0[order[i], order[j]]
            new_P1[i,j] = P1[order[i], order[j]]
        new_R0[i] = R0[order[i]]
        new_R1[i] = R1[order[i]]
        new_states[i] = states[order[i]]
    return new_P0, new_P1, new_R0, new_R1, new_states


"It simulates one step of the restless bandit problem while considering a specific order of states, transitioning between them and calculating the rewards based on that order"

def simulate_one_step_order(states,M,P0,P1,R0,R1,order):
    n = len(order)
    P0,P1,R0,R1,states = sort_data(P0,P1,R0,R1,states,order)
    next_states = simulate_one_step(states,M,P0,P1)   ## The next states generated (next_states) are based on the sorted order
    reward = reward_one_step(states,M,R0,R1)    ## To return the states to their original order, the function uses np.argsort(order) to map the sorted indices back to the original order

    ## Why there is a need of Revert the Ordering of Next States ?
    s = np.argsort(order)    ## Returns the indices that would sort the array  (By default -- Ascending)
    real_next = np.zeros(n, dtype=int)
    for i in range(n):          ## After the simulation step, the function reverts the order of the next states to match the original state order 
        real_next[i] = next_states[s[i]]   ## This ensures that the rest of the system (or downstream processes) sees the states in their original sequence, even though the simulation step might have been conducted using a different order
    return real_next,reward

